#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
plot_pareto.py
Multi-objective Pareto front & Hypervolume visualization + Pareto STL exporter.

Works headless (matplotlib Agg backend) without requiring pandas.
Reads either `results.csv` (semicolon-delimited with Obj_* / Feasible / StlPath / Iteration)
or `pareto_front.json` generated by ParetoFrontCalculator.ExportParetoSummary.

Outputs (in --out or input directory):
  - pareto_front.png
  - hypervolume_progress.png
  - optional --export-stls <dir>: copies all Pareto-optimal STL files + pareto_summary.json
"""

import warnings
warnings.filterwarnings("ignore")

import argparse
import csv
import json
import math
import shutil
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
import numpy as np


def _get(obj: Dict[str, Any], camel: str, pascal: str, default: Any = None) -> Any:
    if camel in obj:
        return obj[camel]
    if pascal in obj:
        return obj[pascal]
    return default


def _parse_float(raw: Any) -> Optional[float]:
    if raw is None:
        return None
    s = str(raw).strip()
    if s == "":
        return None
    try:
        v = float(s)
        return v if math.isfinite(v) else None
    except ValueError:
        return None


def _parse_bool(raw: Any, default: bool = True) -> bool:
    if raw is None:
        return default
    if isinstance(raw, bool):
        return raw
    s = str(raw).strip().lower()
    if s in ("1", "true", "yes"):
        return True
    if s in ("0", "false", "no"):
        return False
    return default


def _compute_non_dominated(points: np.ndarray, directions: List[str]) -> np.ndarray:
    """Compute non-dominated mask on (N, M) objective matrix respecting Minimize/Maximize."""
    n, m = points.shape
    if n == 0 or m == 0:
        return np.zeros(n, dtype=bool)

    min_pts = points.copy()
    for j, d in enumerate(directions):
        if d.lower() == "maximize":
            min_pts[:, j] = -min_pts[:, j]

    mask = np.ones(n, dtype=bool)
    for i in range(n):
        if not mask[i]:
            continue
        for j in range(n):
            if i == j:
                continue
            if np.all(min_pts[j] <= min_pts[i]) and np.any(min_pts[j] < min_pts[i]):
                mask[i] = False
                break
    return mask


def _compute_hypervolume_2d(min_points: np.ndarray, ref_point: Tuple[float, float]) -> float:
    if len(min_points) == 0:
        return 0.0
    r1, r2 = ref_point
    filtered = [(float(p[0]), float(p[1])) for p in min_points if p[0] < r1 and p[1] < r2]
    if not filtered:
        return 0.0
    filtered.sort(key=lambda x: (x[0], x[1]))
    hv = 0.0
    best_y = r2
    for f1, f2 in filtered:
        if f2 < best_y:
            hv += (r1 - f1) * (best_y - f2)
            best_y = f2
    return hv


def _load_from_pareto_json(json_path: Path) -> Dict[str, Any]:
    data = json.loads(json_path.read_text(encoding="utf-8"))
    obj_specs = _get(data, "objectives", "Objectives", []) or []
    evals = _get(data, "evaluations", "Evaluations", None)
    if evals is None:
        evals = _get(data, "points", "Points", []) or []

    obj_names = [_get(o, "name", "Name", "") for o in obj_specs]
    directions = [_get(o, "direction", "Direction", "Minimize") for o in obj_specs]

    rows: List[Dict[str, Any]] = []
    for entry in evals:
        objs = _get(entry, "objectives", "Objectives", {}) or {}
        if not obj_names and objs:
            obj_names = list(objs.keys())
            directions = ["Minimize"] * len(obj_names)
        rows.append(
            {
                "iteration": int(_get(entry, "iteration", "Iteration", 1)),
                "variant": int(_get(entry, "variant", "Variant", 1)),
                "feasible": bool(_get(entry, "feasible", "Feasible", True))
                and not bool(_get(entry, "simulationFailed", "SimulationFailed", False))
                and not bool(_get(entry, "disqualified", "Disqualified", False)),
                "stl_path": str(_get(entry, "stlPath", "StlPath", "") or ""),
                "exported_stl_path": str(_get(entry, "exportedStlPath", "ExportedStlPath", "") or ""),
                "objectives": {k: float(v) for k, v in objs.items() if _parse_float(v) is not None},
                "parameters": _get(entry, "parameters", "Parameters", {}) or {},
            }
        )

    return {
        "obj_names": obj_names,
        "directions": directions,
        "rows": rows,
        "hv_history": _get(data, "hypervolumeHistory", "HypervolumeHistory", []) or [],
    }


def _load_from_results_csv(csv_path: Path, directions_override: Optional[List[str]] = None) -> Dict[str, Any]:
    with csv_path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f, delimiter=";")
        fieldnames = reader.fieldnames or []
        obj_cols = [c for c in fieldnames if c.startswith("Obj_")]
        obj_names = [c[4:] for c in obj_cols]

        if not obj_names:
            # Fallback to Drag / Lift if Obj_ columns do not exist
            for fallback in ("Drag", "Lift"):
                if fallback in fieldnames:
                    obj_cols.append(fallback)
                    obj_names.append(fallback)

        directions: List[str] = []
        for idx, name in enumerate(obj_names):
            if directions_override and idx < len(directions_override):
                directions.append(directions_override[idx])
            elif "lift" in name.lower() or "glide" in name.lower() or "fitness" in name.lower():
                directions.append("Maximize")
            else:
                directions.append("Minimize")

        rows: List[Dict[str, Any]] = []
        for raw in reader:
            it_val = _parse_float(raw.get("Iteration"))
            var_val = _parse_float(raw.get("Variant"))
            iteration = int(it_val) if it_val is not None else 1
            variant = int(var_val) if var_val is not None else 1
            if variant == 99 or iteration == 99:
                continue

            failed = _parse_bool(raw.get("SimulationFailed"), default=False)
            disq = _parse_bool(raw.get("Disqualified"), default=False)
            feas = _parse_bool(raw.get("Feasible"), default=True) and not failed and not disq

            objs: Dict[str, float] = {}
            for col, oname in zip(obj_cols, obj_names):
                val = _parse_float(raw.get(col))
                if val is not None:
                    objs[oname] = val

            rows.append(
                {
                    "iteration": iteration,
                    "variant": variant,
                    "feasible": feas,
                    "stl_path": (raw.get("StlPath") or "").strip(),
                    "exported_stl_path": "",
                    "objectives": objs,
                    "parameters": {},
                }
            )

    return {
        "obj_names": obj_names,
        "directions": directions,
        "rows": rows,
        "hv_history": [],
    }


def _resolve_input(input_path: Path) -> Tuple[Path, str]:
    if input_path.is_file():
        if input_path.suffix.lower() == ".json":
            return input_path, "json"
        return input_path, "csv"
    if input_path.is_dir():
        json_cand = input_path / "pareto_front.json"
        csv_cand = input_path / "results.csv"
        if json_cand.is_file():
            return json_cand, "json"
        if csv_cand.is_file():
            return csv_cand, "csv"
    raise FileNotFoundError(f"Could not find pareto_front.json or results.csv at: {input_path}")


def plot_and_export(
    input_path: Path,
    out_dir: Path,
    export_stls_dir: Optional[Path] = None,
    directions_override: Optional[List[str]] = None,
    dpi: int = 300,
) -> Dict[str, Any]:
    resolved_path, kind = _resolve_input(input_path)
    dataset = (
        _load_from_pareto_json(resolved_path)
        if kind == "json"
        else _load_from_results_csv(resolved_path, directions_override=directions_override)
    )

    obj_names: List[str] = dataset["obj_names"]
    directions: List[str] = dataset["directions"]
    if directions_override:
        for i in range(min(len(directions), len(directions_override))):
            directions[i] = directions_override[i]

    rows: List[Dict[str, Any]] = dataset["rows"]
    if len(obj_names) < 2:
        raise ValueError(f"Need at least 2 objectives for Pareto plotting, found: {obj_names}")

    o1_name, o2_name = obj_names[0], obj_names[1]
    d1, d2 = directions[0], directions[1]

    feas_rows = [
        r
        for r in rows
        if r["feasible"] and o1_name in r["objectives"] and o2_name in r["objectives"]
    ]
    infeas_rows = [
        r
        for r in rows
        if (not r["feasible"]) and o1_name in r["objectives"] and o2_name in r["objectives"]
    ]

    if not feas_rows and not infeas_rows:
        raise ValueError("No rows with valid objective values found.")

    out_dir.mkdir(parents=True, exist_ok=True)

    # Compute Pareto front among feasible rows
    pareto_rows: List[Dict[str, Any]] = []
    pareto_mask = np.zeros(len(feas_rows), dtype=bool)
    if feas_rows:
        pts = np.array(
            [[r["objectives"][o1_name], r["objectives"][o2_name]] for r in feas_rows],
            dtype=np.float64,
        )
        pareto_mask = _compute_non_dominated(pts, [d1, d2])
        pareto_rows = [feas_rows[i] for i in range(len(feas_rows)) if pareto_mask[i]]
        pareto_rows.sort(key=lambda r: r["objectives"][o1_name])

    # 1. Pareto front PNG
    fig, ax = plt.subplots(figsize=(9, 6))
    if infeas_rows:
        ax.scatter(
            [r["objectives"][o1_name] for r in infeas_rows],
            [r["objectives"][o2_name] for r in infeas_rows],
            color="#9e9e9e",
            alpha=0.55,
            s=45,
            marker="x",
            label=f"Infeasible ({len(infeas_rows)})",
            zorder=2,
        )

    if feas_rows:
        iters = np.array([r["iteration"] for r in feas_rows], dtype=float)
        sc = ax.scatter(
            [r["objectives"][o1_name] for r in feas_rows],
            [r["objectives"][o2_name] for r in feas_rows],
            c=iters,
            cmap="viridis",
            alpha=0.80,
            s=55,
            edgecolors="none",
            label=f"Feasible ({len(feas_rows)})",
            zorder=3,
        )
        cbar = fig.colorbar(sc, ax=ax)
        cbar.set_label("Iteration / Generation", fontsize=10)
        cbar.locator = ticker.MaxNLocator(integer=True)
        cbar.update_ticks()

    if pareto_rows:
        px = [r["objectives"][o1_name] for r in pareto_rows]
        py = [r["objectives"][o2_name] for r in pareto_rows]
        ax.plot(
            px,
            py,
            color="#d62728",
            linestyle="--",
            linewidth=2.0,
            marker="o",
            markersize=7,
            markeredgecolor="black",
            markeredgewidth=0.8,
            label=f"Pareto Front ({len(pareto_rows)})",
            zorder=5,
        )

    ax.set_title(f"Pareto Front: {o2_name} vs. {o1_name}", fontsize=13, fontweight="bold")
    ax.set_xlabel(f"{o1_name} [{d1}]", fontsize=11)
    ax.set_ylabel(f"{o2_name} [{d2}]", fontsize=11)
    ax.grid(True, linestyle="--", alpha=0.45)
    ax.legend(loc="best", framealpha=0.9)
    plt.tight_layout()
    pareto_png = out_dir / "pareto_front.png"
    fig.savefig(pareto_png, dpi=dpi, bbox_inches="tight")
    plt.close(fig)

    # 2. Hypervolume progress PNG
    hv_series: List[Tuple[int, float]] = []
    if feas_rows:
        sign1 = -1.0 if d1.lower() == "maximize" else 1.0
        sign2 = -1.0 if d2.lower() == "maximize" else 1.0
        all_min = np.array(
            [[sign1 * r["objectives"][o1_name], sign2 * r["objectives"][o2_name]] for r in feas_rows],
            dtype=np.float64,
        )
        r1 = float(all_min[:, 0].max() + max(0.1 * (all_min[:, 0].max() - all_min[:, 0].min()), 1e-3))
        r2 = float(all_min[:, 1].max() + max(0.1 * (all_min[:, 1].max() - all_min[:, 1].min()), 1e-3))

        unique_iters = sorted(set(r["iteration"] for r in rows))
        for it in unique_iters:
            prefix = [
                [sign1 * r["objectives"][o1_name], sign2 * r["objectives"][o2_name]]
                for r in feas_rows
                if r["iteration"] <= it
            ]
            hv_val = _compute_hypervolume_2d(np.array(prefix, dtype=np.float64), (r1, r2)) if prefix else 0.0
            hv_series.append((it, hv_val))

    fig_hv, ax_hv = plt.subplots(figsize=(8.5, 5))
    if hv_series:
        xs = [p[0] for p in hv_series]
        ys = [p[1] for p in hv_series]
        ax_hv.plot(xs, ys, color="#1f77b4", marker="o", linewidth=2.2, markersize=6, label="Dominated Hypervolume")
        ax_hv.fill_between(xs, 0, ys, color="#1f77b4", alpha=0.12)
    ax_hv.set_title("Hypervolume Progression Over Generations", fontsize=13, fontweight="bold")
    ax_hv.set_xlabel("Iteration / Generation", fontsize=11)
    ax_hv.set_ylabel("2D Hypervolume [-]", fontsize=11)
    ax_hv.xaxis.set_major_locator(ticker.MaxNLocator(integer=True))
    ax_hv.grid(True, linestyle="--", alpha=0.45)
    ax_hv.legend(loc="best")
    plt.tight_layout()
    hv_png = out_dir / "hypervolume_progress.png"
    fig_hv.savefig(hv_png, dpi=dpi, bbox_inches="tight")
    plt.close(fig_hv)

    # 3. Optional STL export
    exported_files: List[str] = []
    if export_stls_dir is not None:
        export_stls_dir.mkdir(parents=True, exist_ok=True)
        base_dir = resolved_path.parent
        pareto_summary_items: List[Dict[str, Any]] = []

        for r in pareto_rows:
            copied_to = ""
            cand_paths = []
            if r["exported_stl_path"]:
                cand_paths.append(Path(r["exported_stl_path"]))
            if r["stl_path"]:
                p_stl = Path(r["stl_path"])
                cand_paths.append(p_stl)
                if not p_stl.is_absolute():
                    cand_paths.append(base_dir / p_stl)

            for src in cand_paths:
                if src.is_file():
                    dest_name = f"pareto_Gen{r['iteration']}_Var{r['variant']}{src.suffix or '.stl'}"
                    dest = export_stls_dir / dest_name
                    shutil.copy2(src, dest)
                    copied_to = str(dest)
                    exported_files.append(copied_to)
                    break

            pareto_summary_items.append(
                {
                    "iteration": r["iteration"],
                    "variant": r["variant"],
                    "objectives": r["objectives"],
                    "parameters": r["parameters"],
                    "stlSource": r["stl_path"],
                    "exportedStl": copied_to,
                }
            )

        summary_json = export_stls_dir / "pareto_summary.json"
        summary_json.write_text(
            json.dumps(
                {
                    "objectives": [{"name": n, "direction": d} for n, d in zip(obj_names, directions)],
                    "paretoCount": len(pareto_rows),
                    "finalHypervolume": hv_series[-1][1] if hv_series else 0.0,
                    "points": pareto_summary_items,
                },
                indent=2,
            ),
            encoding="utf-8",
        )

    return {
        "pareto_png": str(pareto_png),
        "hypervolume_png": str(hv_png),
        "pareto_count": len(pareto_rows),
        "feasible_count": len(feas_rows),
        "final_hypervolume": hv_series[-1][1] if hv_series else 0.0,
        "exported_stls": exported_files,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot Pareto front & Hypervolume from FluidForge results.")
    parser.add_argument("input", nargs="?", default=".", help="Path to results directory, results.csv, or pareto_front.json")
    parser.add_argument("--out", type=str, default=None, help="Output directory for PNG plots")
    parser.add_argument("--export-stls", type=str, default=None, help="Directory to export Pareto-optimal STLs and pareto_summary.json")
    parser.add_argument("--directions", type=str, default=None, help="Comma-separated directions override, e.g. Minimize,Maximize")
    parser.add_argument("--dpi", type=int, default=300, help="PNG DPI resolution (default 300)")
    args = parser.parse_args()

    in_path = Path(args.input).resolve()
    out_dir = Path(args.out).resolve() if args.out else (in_path if in_path.is_dir() else in_path.parent)
    export_dir = Path(args.export_stls).resolve() if args.export_stls else None
    dirs_override = [d.strip() for d in args.directions.split(",") if d.strip()] if args.directions else None

    result = plot_and_export(in_path, out_dir, export_stls_dir=export_dir, directions_override=dirs_override, dpi=args.dpi)
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
